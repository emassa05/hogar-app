  validationError('VALIDATION_ERROR'),
  capacitySumInvalid('CAPACITY_SUM_INVALID'),
  unplannedTaskOutOfRange('UNPLANNED_TASK_OUT_OF_RANGE'),
  accountLocked('ACCOUNT_LOCKED'),
  rateLimited('RATE_LIMITED'),
  verificationAttemptsExceeded('VERIFICATION_ATTEMPTS_EXCEEDED'),
  verificationResendTooSoon('VERIFICATION_RESEND_TOO_SOON'),
  internalError('INTERNAL_ERROR'),
  smsDeliveryFailed('SMS_DELIVERY_FAILED'),
  serviceUnavailable('SERVICE_UNAVAILABLE'),
  unknown('UNKNOWN');

  const ApiErrorCode(this.value);
  final String value;

  static ApiErrorCode fromValue(Object? value) =>
      values.firstWhere((code) => code.value == value, orElse: () => unknown);
}
