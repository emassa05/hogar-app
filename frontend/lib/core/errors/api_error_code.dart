  conflict('CONFLICT'),
  verificationExpired('VERIFICATION_EXPIRED'),
  invitationExpired('INVITATION_EXPIRED'),
  versionConflict('VERSION_CONFLICT'),
  attachmentTooLarge('ATTACHMENT_TOO_LARGE'),
